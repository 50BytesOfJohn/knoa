//! One emoji, as a folder can show in place of a glyph.

use unicode_segmentation::UnicodeSegmentation as _;

use crate::protocol::max_chars::{self, fits};

/// Exactly one emoji: a single grapheme cluster that is pictographic, a flag or a keycap.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct Emoji(String);

impl Emoji {
    /// `None` unless `text` is exactly one emoji, with nothing around it.
    pub fn new(text: &str) -> Option<Emoji> {
        let mut graphemes = text.graphemes(true);
        let single = graphemes.next().is_some() && graphemes.next().is_none();
        (single && fits(text, max_chars::folder::ICON) && is_emoji(text))
            .then(|| Emoji(text.to_owned()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Whether one grapheme cluster reads as an emoji. A flag is two regional indicators and
/// a keycap ends in U+20E3; neither is pictographic on its own.
fn is_emoji(grapheme: &str) -> bool {
    grapheme
        .chars()
        .any(|c| is_pictographic(c) || is_regional_indicator(c) || c == '\u{20E3}')
}

fn is_regional_indicator(c: char) -> bool {
    ('\u{1F1E6}'..='\u{1F1FF}').contains(&c)
}

fn is_pictographic(c: char) -> bool {
    let code = u32::from(c);
    PICTOGRAPHIC
        .binary_search_by(|&(start, end)| {
            if end < code {
                std::cmp::Ordering::Less
            } else if start > code {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

